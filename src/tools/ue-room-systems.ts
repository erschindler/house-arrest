/**
 * UE5 emitters for the room-first build.
 *
 * `ue-systems.ts` emits the simulation-facing components (anatomy, session,
 * confinement, leverage, the hidden room). This module emits the *physical* half
 * that the room needs before anything else in the game matters:
 *
 *   surface.ts        -> UHASPhysicsContactComponent  (bone -> region, sweep -> wound)
 *   wounds + blood    -> UHASWoundComponent           (channel geometry, decals, pooling)
 *   severance         -> UHASDismembermentComponent   (joint progress, stump, detached limb)
 *   voice/expression  -> UHASVoiceComponent           (cue selection, male/female sets, morphs)
 *   camera + market   -> UHASProductionComponent      (footage, camera tier, listings, payouts)
 *
 * The rule from the other emitter still holds: gating is never re-implemented in
 * C++. A decal, a stump cap or a scream asks `UHASContentSubsystem::HasAssetClass`
 * and does nothing if the class was not registered.
 *
 * There are no sexual surfaces, sexual interactions or genital collision in this
 * layer. The room is a violence system: every contact it resolves is damage, and
 * the only hands it tracks are the player's and the victim's.
 *
 * None of this has been compiled — there is no engine in this repository.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

function write(outDir: string, relative: string, contents: string, written: string[]): void {
  const target = join(outDir, relative);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents);
  written.push(relative);
}

