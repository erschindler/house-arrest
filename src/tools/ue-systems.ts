/**
 * UE5 system emitters.
 *
 * `ue5.ts` emits the *content* half of the integration (a plugin and a registry
 * of asset classes). This emits the *gameplay* half: the C++ components that the
 * simulation core's five new systems map onto, the data tables that drive them,
 * and the editor script that builds the concealed room in a level.
 *
 * The mapping is deliberate and one-directional:
 *
 *   confinement.ts  -> UHASConfinementComponent   (fear/anxiety/threshold)
 *   manipulation.ts -> UHASManipulationComponent  (leverage, accomplices, orders)
 *   facility.ts     -> UHASHiddenRoomComponent    (build stages, sound, concealment)
 *   anatomy.ts      -> UHASAnatomyComponent       (organs, limbs, wounds, vitals)
 *   torture.ts      -> UHASTortureSessionComponent (acts, gating, session state)
 *
 * Rules followed here:
 *   - Gating is not re-implemented in C++. Every act asks the content subsystem
 *     whether its asset class is registered; if the registry excluded it, the act
 *     is refused. One source of truth.
 *   - Anatomy state is data (TArray, not TMap with enum keys) so it serialises,
 *     replicates and lands in a DataTable without custom hashing.
 *   - No timestamps, no floats formatted with locale, so output is byte-stable.
 *
 * None of this has been through a compiler: there is no engine in this
 * repository. Treat the first build as a debugging session, not a formality.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

function write(outDir: string, relative: string, contents: string, written: string[]): void {
  const target = join(outDir, relative);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents);
  written.push(relative);
}

