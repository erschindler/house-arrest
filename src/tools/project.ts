/**
 * Unreal project scaffold.
 *
 * The installer writes the *content* half of a UE integration (a plugin plus a
 * registry). This writes the other half: a minimal, compilable C++ game project
 * that already depends on that plugin, plus the two Python scripts the pipeline
 * runs inside the editor to import a Fab drop folder and to verify that every
 * path in the registry actually exists afterwards.
 *
 * Everything here is generated text. The .uproject, targets and module files are
 * ordinary boilerplate that a UE 5.4/5.5 project would contain; the Python is
 * written against the documented editor API. None of it has been executed in
 * this repository — there is no engine here — so treat the first run as a
 * debugging session rather than a formality.
 *
 * No timestamps: the scaffold is byte-identical for the same inputs.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { stableStringify } from "../save/serialize.ts";
import { emitSystems } from "./ue-systems.ts";
import { emitRoomSystems } from "./ue-room-systems.ts";

export type ProjectOptions = {
  /** Module and project name. Must be a valid C++ identifier. */
  projectName: string;
  /** Value for EngineAssociation, e.g. "5.5". */
  engineAssociation: string;
  /**
   * Level the editor and the packaged game start in. Null keeps the engine's Entry
   * map, which is what an engine-less run has to do: the room stage is what creates
   * the level, so naming it without an engine would point at an asset that is never
   * made.
   */
  defaultMap?: string | null;
};

function write(outDir: string, relative: string, contents: string, written: string[]): void {
  const target = join(outDir, relative);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents);
  written.push(relative);
}

function uprojectFile(options: ProjectOptions): string {
  return `${stableStringify({
    FileVersion: 3,
    EngineAssociation: options.engineAssociation,
    Category: "Game",
    Description: "HOUSE ARREST — generated by the house-arrest pipeline.",
    Modules: [{ Name: options.projectName, Type: "Runtime", LoadingPhase: "Default" }],
    Plugins: [
      { Name: "HASContent", Enabled: true },
      // Both are required for the headless stages below: -run=pythonscript needs
      // the Python plugin, and EditorAssetLibrary/EditorStaticMeshLibrary live in
      // EditorScriptingUtilities.
      { Name: "PythonScriptPlugin", Enabled: true },
      { Name: "EditorScriptingUtilities", Enabled: true },
    ],
  })}\n`;
}

function targetFile(options: ProjectOptions, editor: boolean): string {
  const name = options.projectName;
  return `// GENERATED by src/tools/project.ts — do not edit by hand.
using UnrealBuildTool;
using System.Collections.Generic;

public class ${name}${editor ? "Editor" : ""}Target : TargetRules
{
    public ${name}${editor ? "Editor" : ""}Target(TargetInfo Target) : base(Target)
    {
        Type = TargetType.${editor ? "Editor" : "Game"};
        // Latest, not a pinned V5: an installed engine builds UnrealEditor with its
        // own newest defaults, and a game target that pins an older version sets
        // those properties to different values. UBT refuses that outright
        // ("modifies the values of properties ... has build products in common with
        // UnrealEditor") unless the target gets a unique build environment.
        DefaultBuildSettings = BuildSettingsVersion.Latest;
        IncludeOrderVersion = EngineIncludeOrderVersion.Latest;
        ExtraModuleNames.Add("${name}");
    }
}
`;
}

function moduleBuildFile(options: ProjectOptions): string {
  const name = options.projectName;
  return `// GENERATED by src/tools/project.ts — do not edit by hand.
using UnrealBuildTool;

public class ${name} : ModuleRules
{
    public ${name}(ReadOnlyTargetRules Target) : base(Target)
    {
        PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;

        PublicDependencyModuleNames.AddRange(new string[] {
            "Core",
            "CoreUObject",
            "Engine",
            "InputCore",
            "HASContent"
        });

        // Json/JsonUtilities are for the data tables the systems emitter writes.
        PublicDependencyModuleNames.AddRange(new string[] { "Json", "JsonUtilities" });
    }
}
`;
}

function moduleHeaderFile(options: ProjectOptions): string {
  return `// GENERATED by src/tools/project.ts — do not edit by hand.
#pragma once

#include "CoreMinimal.h"
`;
}

function moduleSourceFile(options: ProjectOptions): string {
  const name = options.projectName;
  return `// GENERATED by src/tools/project.ts — do not edit by hand.
#include "${name}.h"
#include "Modules/ModuleManager.h"

IMPLEMENT_PRIMARY_GAME_MODULE(FDefaultGameModuleImpl, ${name}, "${name}");
`;
}

function defaultEngineIni(options: ProjectOptions): string {
  const start = options.defaultMap ?? "/Engine/Maps/Entry";
  return `; GENERATED by src/tools/project.ts — do not edit by hand.
[/Script/EngineSettings.GameMapsSettings]
GameDefaultMap=${start}
EditorStartupMap=${start}

[/Script/Engine.Engine]
+ActiveGameNameRedirects=(OldGameName="TP_Blank",NewGameName="/Script/${options.projectName}")

[/Script/WindowsTargetPlatform.WindowsTargetSettings]
; Shader Model 6 carries Nanite and Lumen. Without it the editor opens with a "Missing
; Project Settings" dialog and any Nanite mesh draws as its fallback, so it is part of
; the scaffold rather than something to fix by hand after the first launch - this file
; is rewritten on every run, which would silently undo a dialog-saved setting.
DefaultGraphicsRHI=DefaultGraphicsRHI_DX12
+TargetedShaderFormats=PCD3D_SM6
-TargetedShaderFormats=PCD3D_SM5
`;
}

function defaultGameIni(): string {
  return `; GENERATED by src/tools/project.ts — do not edit by hand.
[/Script/EngineSettings.GeneralProjectSettings]
ProjectName=HOUSE ARREST
ProjectVersion=0.1.0
bStartInVR=False

[/Script/UnrealEd.ProjectPackagingSettings]
BuildConfiguration=PPBC_Development
bSkipEditorContent=True
`;
}

/**
 * Runs inside the editor. Walks a drop folder, imports everything it recognises
 * into /Game/HASContent, and writes an index in the *same schema* the offline
 * library reader consumes — so the next pipeline pass resolves against what
 * really landed in the engine instead of what a spreadsheet claimed.
 */
function importScript(): string {
  return `"""GENERATED by src/tools/project.ts — do not edit by hand.

Import a Fab drop folder into the project, headless:

    UnrealEditor-Cmd <project>.uproject -run=pythonscript \\
        -script="<project>/Scripts/has_import.py" -unattended -nopause -nosplash

Environment:
    HAS_DROP_DIR     folder containing the extracted Fab packs (required)
    HAS_IMPORT_JSON  output index path (same schema as the installer library)

Writes an index of what was imported so the resolver can be re-run against it.
This script has not been executed outside a real editor.
"""

import json
import os
import re
import shutil
import sys

import unreal

DEST_ROOT = "/Game/HASContent"

EXTENSIONS = {
    ".fbx": "mesh",
    ".obj": "mesh",
    ".abc": "animation",
    ".png": "material",
    ".tga": "material",
    ".exr": "material",
    ".wav": "prop",
}

MESH_EXTENSIONS = (".fbx", ".obj")
PACKED_EXTENSIONS = (".uasset", ".umap")

# Fab packs usually ship as built content, not as source files. The class name of the
# asset decides which library kind it is indexed as.
KIND_BY_CLASS = {
    "StaticMesh": "mesh",
    "SkeletalMesh": "mesh",
    "Material": "material",
    "MaterialInstance": "material",
    "MaterialInstanceConstant": "material",
    "AnimSequence": "animation",
    "AnimMontage": "animation",
    "Blueprint": "prop",
}


def say(message):
    # print() is block-buffered inside the commandlet and is lost when the script
    # exits non-zero, which is exactly when the message matters. The log always keeps
    # it, so every diagnostic goes to both.
    print(message)
    unreal.log(message)


def importable_files(root):
    found = []
    for base, _dirs, files in os.walk(root):
        for name in sorted(files):
            extension = os.path.splitext(name)[1].lower()
            if extension in EXTENSIONS:
                found.append(os.path.join(base, name))
    found.sort()
    return found


def tags_for(name):
    cleaned = os.path.splitext(name)[0]
    for separator in ("-", " ", ".", "/"):
        cleaned = cleaned.replace(separator, "_")
    tokens = []
    for chunk in cleaned.split("_"):
        # SM_BasementInterior has to be able to match the keyword "basement", so the
        # CamelCase the packs use is split rather than kept as one long token.
        for part in re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", chunk).split("_"):
            if part:
                tokens.append(part.lower())
    return tokens


def describe(asset_path, kind, name, pack):
    entry = {
        "id": asset_path,
        "name": name,
        "kind": kind,
        "tags": tags_for(name),
        "triangles": 0,
        "lods": 1,
        "animated": kind == "animation",
        "license": "user-supplied drop folder - verify before shipping",
        "pack": pack,
    }
    if kind != "mesh":
        return entry

    mesh = unreal.EditorAssetLibrary.load_asset(asset_path)
    if mesh is None:
        return entry
    try:
        entry["triangles"] = int(unreal.EditorStaticMeshLibrary.get_number_triangles(mesh))
        entry["lods"] = int(unreal.EditorStaticMeshLibrary.get_lod_count(mesh))
    except Exception as error:  # noqa: BLE001 - diagnostics only
        say("HAS: could not measure %s: %s" % (asset_path, error))
    return entry


def packed_assets(root):
    found = []
    for base, _dirs, files in os.walk(root):
        for name in sorted(files):
            if os.path.splitext(name)[1].lower() in PACKED_EXTENSIONS:
                found.append(os.path.join(base, name))
    found.sort()
    return found


def extension_census(root):
    counts = {}
    for base, _dirs, files in os.walk(root):
        for name in files:
            extension = os.path.splitext(name)[1].lower() or "(none)"
            counts[extension] = counts.get(extension, 0) + 1
    if not counts:
        return "the folder is empty"
    return ", ".join("%s=%d" % (key, counts[key]) for key in sorted(counts))


def relative_under_content(path, root):
    """Strip the pack wrapper, including a literal Content/ folder, from a path."""
    parts = os.path.relpath(path, root).replace("\\\\", "/").split("/")
    if "Content" in parts:
        parts = parts[parts.index("Content") + 1:]
    return [part for part in parts if part]


def write_index(entries):
    out_path = os.environ.get("HAS_IMPORT_JSON", "")
    if not out_path:
        out_path = os.path.join(unreal.Paths.project_dir(), "Saved", "has_imported.json")

    payload = {"pack": "imported drop folder", "assets": entries}
    directory = os.path.dirname(out_path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    with open(out_path, "w") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True)
    return out_path


def adopt_content_pack(drop, packed):
    """A pack of .uasset files is already engine content: copy it in, do not import.

    Copying under Content/HASContent keeps the pack's own folder layout out of the
    project root, and the asset registry finds the files there.
    """
    content = unreal.Paths.project_content_dir().replace("\\\\", "/").rstrip("/")
    planned = []
    copied = 0

    for path in packed:
        parts = relative_under_content(path, drop)
        if not parts:
            continue
        destination = os.path.join(content, "HASContent", *parts)
        directory = os.path.dirname(destination)
        if directory and not os.path.isdir(directory):
            os.makedirs(directory)
        shutil.copy2(path, destination)
        copied += 1
        if parts[-1].lower().endswith(".umap"):
            continue
        stem = os.path.splitext(parts[-1])[0]
        planned.append(
            {
                "path": DEST_ROOT + "/" + "/".join(parts[:-1] + [stem]),
                "name": stem,
                "pack": "/".join(parts[:-1]) or "pack",
            }
        )

    say("HAS: copied %d pack files into %s/HASContent" % (copied, content))

    registry = unreal.AssetRegistryHelpers.get_asset_registry()
    try:
        registry.scan_paths_synchronous([DEST_ROOT], True, True)
    except Exception as error:  # noqa: BLE001 - the signature differs across versions
        say("HAS: registry rescan failed (%s); reading what is on disk" % error)

    entries = []
    failures = []
    for item in planned:
        if not unreal.EditorAssetLibrary.does_asset_exist(item["path"]):
            failures.append(item["path"])
            continue
        asset = unreal.EditorAssetLibrary.load_asset(item["path"])
        class_name = asset.get_class().get_name() if asset is not None else ""
        entry = describe(item["path"], KIND_BY_CLASS.get(class_name, "prop"), item["name"], item["pack"])
        if class_name:
            entry["tags"] = sorted(set(entry["tags"] + [class_name.lower()]))
        entries.append(entry)

    write_index(entries)
    say("HAS: adopted %d assets, %d unreadable" % (len(entries), len(failures)))
    for path in failures:
        say("HAS: could not read %s" % path)
    return 0 if entries else 1


def main():
    drop = os.environ.get("HAS_DROP_DIR", "")
    if not drop or not os.path.isdir(drop):
        unreal.log_error("HAS: HAS_DROP_DIR is not a directory: %r" % drop)
        return 2

    files = importable_files(drop)
    if not files:
        packed = packed_assets(drop)
        if packed:
            return adopt_content_pack(drop, packed)
        unreal.log_error(
            "HAS: nothing importable under %s - %s" % (drop, extension_census(drop))
        )
        return 2

    tasks = []
    planned = []
    for path in files:
        relative = os.path.relpath(path, drop).replace(os.sep, "/")
        folder = os.path.dirname(relative)
        stem = os.path.splitext(os.path.basename(relative))[0]
        destination = DEST_ROOT + "/" + folder if folder else DEST_ROOT

        task = unreal.AssetImportTask()
        task.filename = path
        task.destination_path = destination
        task.destination_name = stem
        task.automated = True
        task.replace_existing = True
        task.save = True
        tasks.append(task)

        planned.append(
            {
                "path": destination + "/" + stem,
                "name": stem,
                "kind": EXTENSIONS[os.path.splitext(path)[1].lower()],
                "pack": folder or "drop",
            }
        )

    say("HAS: importing %d files into %s" % (len(tasks), DEST_ROOT))
    try:
        unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)
    except Exception as error:  # noqa: BLE001 - the engine raises on unusable files
        unreal.log_error("HAS: import_asset_tasks raised: %s" % error)
        return 2

    entries = []
    failures = []
    for item in planned:
        if not unreal.EditorAssetLibrary.does_asset_exist(item["path"]):
            failures.append(item["path"])
            continue
        entries.append(describe(item["path"], item["kind"], item["name"], item["pack"]))

    out_path = write_index(entries)
    say("HAS: imported %d, failed %d, index written to %s" % (len(entries), len(failures), out_path))
    for path in failures:
        say("HAS: failed to import %s" % path)

    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
`;
}

/**
 * Runs inside the editor after the import. Fails the pipeline if the registry
 * points at anything the engine does not actually have — the difference between
 * "the installer said it resolved" and "the game can load it".
 */
function verifyScript(): string {
  return `"""GENERATED by src/tools/project.ts — do not edit by hand.

Verify that every path in the content registry exists in the engine:

    UnrealEditor-Cmd <project>.uproject -run=pythonscript \\
        -script="<project>/Scripts/has_verify.py" -unattended -nopause -nosplash

Environment:
    HAS_REGISTRY  registry path (defaults to the plugin's copy in this project)

Exits non-zero if a single registered class cannot be loaded.
"""

import json
import os
import sys

import unreal

DEFAULT_REGISTRY = os.path.join(
    unreal.Paths.project_dir(),
    "Plugins",
    "HASContent",
    "Content",
    "Data",
    "HASAssetRegistry.json",
)


def main():
    registry_path = os.environ.get("HAS_REGISTRY", "") or DEFAULT_REGISTRY
    if not os.path.isfile(registry_path):
        print("HAS: registry not found at %s - run the content stage first" % registry_path)
        return 2

    with open(registry_path) as handle:
        registry = json.load(handle)

    entries = registry.get("entries", [])
    print("HAS: verifying %d registered content classes" % len(entries))

    missing = []
    for entry in entries:
        asset_path = entry.get("path", "")
        if not asset_path:
            missing.append("%s (empty path)" % entry.get("assetClass", "?"))
            continue
        if not unreal.EditorAssetLibrary.does_asset_exist(asset_path):
            missing.append("%s -> %s" % (entry.get("assetClass", "?"), asset_path))

    if missing:
        print("HAS: %d registered classes are missing from the engine:" % len(missing))
        for line in missing:
            print("  - %s" % line)
        return 1

    print("HAS: all registered classes resolve. safe to build.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
`;
}

export function emitProject(outDir: string, options: ProjectOptions): string[] {
  const written: string[] = [];
  const name = options.projectName;

  write(outDir, `${name}.uproject`, uprojectFile(options), written);
  write(outDir, `Source/${name}.Target.cs`, targetFile(options, false), written);
  write(outDir, `Source/${name}Editor.Target.cs`, targetFile(options, true), written);
  write(outDir, `Source/${name}/${name}.Build.cs`, moduleBuildFile(options), written);
  write(outDir, `Source/${name}/${name}.h`, moduleHeaderFile(options), written);
  write(outDir, `Source/${name}/${name}.cpp`, moduleSourceFile(options), written);
  write(outDir, "Config/DefaultEngine.ini", defaultEngineIni(options), written);
  write(outDir, "Config/DefaultGame.ini", defaultGameIni(), written);
  write(outDir, "Scripts/has_import.py", importScript(), written);
  write(outDir, "Scripts/has_verify.py", verifyScript(), written);

  // The gameplay half: components, data tables and the room-build script.
  written.push(...emitSystems(outDir, name));

  // The physical half: contact, wounds, blood, dismemberment, voice, production.
  written.push(...emitRoomSystems(outDir, name));

  return written;
}
